package com.harriswebstudio.router.http;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

@Getter
@RequiredArgsConstructor
public enum HttpStatus {

    // 1xx Informational
    CONTINUE(100, HttpResponse.INFORMATIONAL),
    SWITCHING_PROTOCOLS(101, HttpResponse.INFORMATIONAL),
    EARLY_HINTS(103, HttpResponse.INFORMATIONAL),

    // 2xx Success
    OK(200, HttpResponse.SUCCESSFUL),
    CREATED(201, HttpResponse.SUCCESSFUL),
    ACCEPTED(202, HttpResponse.SUCCESSFUL),
    NON_AUTHORITATIVE_INFORMATION(203, HttpResponse.SUCCESSFUL),
    NO_CONTENT(204, HttpResponse.SUCCESSFUL),
    RESET_CONTENT(205, HttpResponse.SUCCESSFUL),
    PARTIAL_CONTENT(206, HttpResponse.SUCCESSFUL),
    MULTI_STATUS(207, HttpResponse.SUCCESSFUL),
    ALREADY_REPORTED(208, HttpResponse.SUCCESSFUL),
    IM_USED(226, HttpResponse.SUCCESSFUL),

    // 3xx Redirection
    MULTIPLE_CHOICES(300, HttpResponse.REDIRECTION),
    MOVED_PERMANENTLY(301, HttpResponse.REDIRECTION),
    FOUND(302, HttpResponse.REDIRECTION),
    SEE_OTHER(303, HttpResponse.REDIRECTION),
    NOT_MODIFIED(304, HttpResponse.REDIRECTION),
    TEMPORARY_REDIRECT(307, HttpResponse.REDIRECTION),
    PERMANENT_REDIRECT(308, HttpResponse.REDIRECTION),

    // 4xx Client Error
    BAD_REQUEST(400, HttpResponse.CLIENT_ERROR),
    UNAUTHORIZED(401, HttpResponse.CLIENT_ERROR),
    PAYMENT_REQUIRED(402, HttpResponse.CLIENT_ERROR),
    FORBIDDEN(403, HttpResponse.CLIENT_ERROR),
    NOT_FOUND(404, HttpResponse.CLIENT_ERROR),
    METHOD_NOT_ALLOWED(405, HttpResponse.CLIENT_ERROR),
    NOT_ACCEPTABLE(406, HttpResponse.CLIENT_ERROR),
    PROXY_AUTHENTICATION_REQUIRED(407, HttpResponse.CLIENT_ERROR),
    REQUEST_TIMEOUT(408, HttpResponse.CLIENT_ERROR),
    CONFLICT(409, HttpResponse.CLIENT_ERROR),
    GONE(410, HttpResponse.CLIENT_ERROR),
    LENGTH_REQUIRED(411, HttpResponse.CLIENT_ERROR),
    PRECONDITION_FAILED(412, HttpResponse.CLIENT_ERROR),
    CONTENT_TOO_LARGE(413, HttpResponse.CLIENT_ERROR),
    URI_TOO_LONG(414, HttpResponse.CLIENT_ERROR),
    UNSUPPORTED_MEDIA_TYPE(415, HttpResponse.CLIENT_ERROR),
    REQUESTED_RANGE_NOT_SATISFIABLE(416, HttpResponse.CLIENT_ERROR),
    EXPECTATION_FAILED(417, HttpResponse.CLIENT_ERROR),
    MISDIRECTED_REQUEST(421, HttpResponse.CLIENT_ERROR),
    UNPROCESSABLE_CONTENT(422, HttpResponse.CLIENT_ERROR),
    LOCKED(423, HttpResponse.CLIENT_ERROR),
    FAILED_DEPENDENCY(424, HttpResponse.CLIENT_ERROR),
    TOO_EARLY(425, HttpResponse.CLIENT_ERROR),
    UPGRADE_REQUIRED(426, HttpResponse.CLIENT_ERROR),
    PRECONDITION_REQUIRED(428, HttpResponse.CLIENT_ERROR),
    TOO_MANY_REQUESTS(429, HttpResponse.CLIENT_ERROR),
    REQUEST_HEADER_FIELDS_TOO_LARGE(431, HttpResponse.CLIENT_ERROR),
    UNAVAILABLE_FOR_LEGAL_REASONS(451, HttpResponse.CLIENT_ERROR),

    // 5xx Server Error
    INTERNAL_SERVER_ERROR(500, HttpResponse.SERVER_ERROR),
    NOT_IMPLEMENTED(501, HttpResponse.SERVER_ERROR),
    BAD_GATEWAY(502, HttpResponse.SERVER_ERROR),
    SERVICE_UNAVAILABLE(503, HttpResponse.SERVER_ERROR),
    GATEWAY_TIMEOUT(504, HttpResponse.SERVER_ERROR),
    HTTP_VERSION_NOT_SUPPORTED(505, HttpResponse.SERVER_ERROR),
    VARIANT_ALSO_NEGOTIATES(506, HttpResponse.SERVER_ERROR),
    INSUFFICIENT_STORAGE(507, HttpResponse.SERVER_ERROR),
    LOOP_DETECTED(508, HttpResponse.SERVER_ERROR),
    NETWORK_AUTHENTICATION_REQUIRED(511, HttpResponse.SERVER_ERROR);

    private final int code;
    private final HttpResponse response;

}